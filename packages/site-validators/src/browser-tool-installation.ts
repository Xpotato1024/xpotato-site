async function optional(path:string){try{await noToolLinks(path);return await readFile(path,"utf8");}catch(e){if((e as NodeJS.ErrnoException).code==="ENOENT")return null;throw e;}}
async function load(root:string){return configuration.parse(JSON.parse(await readFile(join(root,configPath),"utf8")));}
const reviewPath=(pin:BrowserToolPin)=>"docs/acceptance/browser-tools/"+pin.toolId+"/"+pin.releaseId+"-source-review.json";
const header="// Generated by browser-tools:install. Edit installations.json through the installer.\n";
function render(c:Configuration):Map<string,string>{
 const files=new Map<string,string>(),modules:Record<string,unknown>={},bindings:unknown[]=[],pins:BrowserToolPin[]=[],imports:string[]=[],components:string[]=[],manifestImports:string[]=[],manifests:string[]=[];
 for(const [i,{pin,placement:p}]of c.installations.entries()){
  const componentId=pin.toolId+"-react-v1",base="bt"+i,dir=pin.toolId+"/"+pin.releaseId;
  modules[pin.toolId]=interactiveModuleRecordSchema.parse({id:pin.toolId,framework:"react",componentId,hydration:p.hydration,allowedCollections:["tools"],role:"primary_tool",status:"active",apiVersion:1,budgetClass:"large",releaseId:pin.releaseId});
  bindings.push(toolBindingRecordSchema.parse({contentId:p.contentId,moduleId:pin.toolId,role:"primary_tool",status:"active"}));pins.push(pin);
  for(const h of ["load","idle","visible","media"]){
   const key=base+h,file=pin.toolId+"-"+h+".astro";
   imports.push('import '+key+' from "./'+file+'";');
   files.set(generatedRoot+"/"+file,'---\nimport Tool from "'+pin.packageName+'";\n'+
    (h==="media"?'interface Props { mediaQuery?:string }\nconst {mediaQuery}=Astro.props;\nif(!mediaQuery)throw Error("Registry-owned mediaQuery required");\n':'')+
    'import "../../../../../../vendor/browser-tools/'+dir+'/'+ // relative from generated directory: src/content-registry/interactive/generated to root
    '__STYLE__";\n---\n<Tool client:'+h+(h==="media"?'={mediaQuery}':'')+' />\n');
  }
  components.push(JSON.stringify(componentId)+":{load:"+base+"load,idle:"+base+"idle,visible:"+base+"visible,media:"+base+"media}");
  manifestImports.push('import '+base+'Manifest from "../../../../../../vendor/browser-tools/'+dir+'/browser-tool.json?raw";');
  manifests.push(JSON.stringify(pin.toolId+":"+pin.releaseId)+":"+base+"Manifest");
  const front={id:p.contentId,title:p.title,description:p.description,pubDate:p.pubDate,category:p.category,tags:p.tags,draft:true};
  files.set("apps/site/src/content/tools/"+p.slug+".mdx","---\n"+Object.entries(front).map(([k,v])=>JSON.stringify(k)+": "+JSON.stringify(v)).join("\n")+"\n---\n\n<Demo module="+JSON.stringify(pin.toolId)+" />\n");
 }
 files.set(generatedRoot+"/records.ts",header+'import {interactiveModuleRecordSchema} from "@xpotato/content-contracts";\nexport const generatedModules = Object.fromEntries(Object.entries('+JSON.stringify(modules,null,2)+').map(([key,value])=>[key,interactiveModuleRecordSchema.parse(value)]));\nexport const generatedBindings = '+JSON.stringify(bindings,null,2)+' as const;\nexport const generatedReleases = '+JSON.stringify(pins,null,2)+' as const;\nexport const generatedComponentIds = '+JSON.stringify(c.installations.map(x=>x.pin.toolId+"-react-v1"))+' as const;\n');
 files.set(generatedRoot+"/components.ts",header+imports.join("\n")+'\nexport const generatedComponents = {'+components.join(",")+'};\n');
 files.set(generatedRoot+"/manifests.ts",header+manifestImports.join("\n")+'\nexport const generatedManifestSources = {'+manifests.join(",")+'};\n');
 return files;
}
async function generatedFiles(root:string,c:Configuration){
 const files=render(c);
 for(const {pin}of c.installations){
  const manifest=await verifyToolPin(join(root,"vendor/browser-tools"),pin);
  for(const h of ["load","idle","visible","media"]){
   const path=generatedRoot+"/"+pin.toolId+"-"+h+".astro";
   const imports=manifest.integration.styles.map(s=>'import "../../../../../../vendor/browser-tools/'+pin.toolId+'/'+pin.releaseId+'/'+s+'";').join("\n");
   files.set(path,files.get(path)!.replace(/import "[^"\n]+__STYLE__";/u,()=>imports));
  }
 }
 return files;
}
async function checkIdentity(root:string,c:Configuration){
 const keys=new Set<string>(),ids=new Set<string>(),routes=new Set<string>();
 // Legacy registration stays stable; new tools use the generated record rather than editing it.
 const legacy=await readFile(join(root,"apps/site/src/content-registry/interactive/index.ts"),"utf8"),manual=new Set<string>();
 const ast=ts.createSourceFile("index.ts",legacy,ts.ScriptTarget.Latest,true,ts.ScriptKind.TS);let registryFound=false;
 const scan=(node:ts.Node):void=>{
  if(ts.isVariableDeclaration(node)&&ts.isIdentifier(node.name)&&node.name.text==="interactiveModuleRegistry"&&node.initializer
   &&ts.isCallExpression(node.initializer)&&node.initializer.arguments[0]&&ts.isObjectLiteralExpression(node.initializer.arguments[0])){
   registryFound=true;for(const prop of node.initializer.arguments[0].properties){
    if(ts.isSpreadAssignment(prop)&&prop.expression.getText(ast)==="generatedModules")continue;
    if(!ts.isPropertyAssignment(prop)||!(ts.isIdentifier(prop.name)||ts.isStringLiteral(prop.name)))throw Error("Unknown manual registry shape; explicit migration required");
    manual.add(prop.name.text);
   }
  }ts.forEachChild(node,scan);
 };scan(ast);if(!registryFound)throw Error("Manual registry shape not recognized");
 for(const {pin,placement:p}of c.installations){
  if(pin.toolId==="prime-factorizer"||manual.has(pin.toolId)||keys.has(pin.toolId)||ids.has(p.contentId)||routes.has(p.slug))throw Error("Duplicate/legacy tool, ContentId or route");
  keys.add(pin.toolId);ids.add(p.contentId);routes.add(p.slug);
 }
 // Identity collision check includes held/draft content, not just published catalog.
 const content=join(root,"apps/site/src/content");
 async function walk(dir:string){for(const e of await readdir(dir,{withFileTypes:true})){
  const path=join(dir,e.name);if(e.isSymbolicLink())throw Error("Content links forbidden");if(e.isDirectory())await walk(path);else if(/\.mdx?$/u.test(e.name)){
   const owned=c.installations.find(x=>path===join(content,"tools",x.placement.slug+".mdx"));if(owned)continue;
   const text=await readFile(path,"utf8");for(const id of ids)if(text.includes(id))throw Error("ContentId already used");
  }
 }}await walk(content);
 // Registry terms must exist; never silently allocate taxonomy.
 const source=await readFile(join(root,"apps/site/src/content-registry/taxonomy/phase5-generated.ts"),"utf8");
 const taxonomy=taxonomyRegistrySchema.parse(JSON.parse(source.slice(source.indexOf("{"),source.lastIndexOf("}")+1)));
 for(const {placement:p}of c.installations){
  if(!taxonomy.toolCategories.some(t=>t.id===p.category&&t.status==="active")||p.tags.some(t=>!taxonomy.tags.some(x=>x.id===t&&x.status==="active")))throw Error("Unknown/inactive Tools taxonomy");
 }
}
export async function checkBrowserToolInstallations(root:string):Promise<void>{
 const c=await load(root);await checkIdentity(root,c);const files=await generatedFiles(root,c);
 for(const[path,text]of files)if(await optional(join(root,path))!==text)throw Error("Stale generated installation: "+path);
 let count=0;
 async function exact(dir:string){for(const e of await readdir(join(root,dir),{withFileTypes:true})){
  if(++count>256)throw Error("Generated directory exceeds budget");
  const path=dir+"/"+e.name;await noToolLinks(join(root,path));
  if(e.isDirectory())await exact(path);else if(!e.isFile()||!files.has(path))throw Error("Unmanaged generated file collision: "+path);
 }}await exact(generatedRoot);
 for(const {pin}of c.installations){
  await noToolLinks(join(root,reviewPath(pin)));
  const review=browserToolReviewSchema.parse(JSON.parse(await readFile(join(root,reviewPath(pin)),"utf8")));
  if((review.source.kind==="local-fixture")!==(review.review.scope==="fixture-only")||toolHash(JSON.stringify(review))!==pin.reviewSha256
   ||JSON.stringify(review.source)!==JSON.stringify(pin.source)
   ||(["sourceCommit","sourceTreeSha256","lockSha256","manifestSha256","artifactSha256"] as const).some(key=>review[key]!==pin[key])
   ||review.reproducibleArtifactSha256.some(hash=>hash!==pin.artifactSha256))throw Error("Durable review identity/hashes do not match pin");
  const pkg=JSON.parse(await readFile(join(root,"apps/site/package.json"),"utf8"));
  const vendor="vendor/browser-tools/"+pin.toolId+"/"+pin.releaseId,dependency="file:../../"+vendor;
  if(pkg.dependencies?.[pin.packageName]!==dependency)throw Error("Installation dependency differs");
  const lock=JSON.parse(await readFile(join(root,"package-lock.json"),"utf8")),manifest=JSON.parse(await readFile(join(root,vendor,"browser-tool.json"),"utf8"));
  if(manifest.runtime.profile==="bounded-browser-v2"&&!review.runtimeReview)throw Error("Durable bounded runtime review required");
  if(lock.packages?.["apps/site"]?.dependencies?.[pin.packageName]!==dependency
   ||lock.packages?.["node_modules/"+pin.packageName]?.resolved!==vendor||lock.packages?.["node_modules/"+pin.packageName]?.link!==true
   ||lock.packages?.[vendor]?.name!==pin.packageName||lock.packages?.[vendor]?.version!==manifest.version)throw Error("Installation lock differs from selected artifact");
 }
}
async function installBrowserToolUnlocked(input:{siteRoot:string;sourceRoot:string;artifactRoot:string;review:unknown;releaseId:string;placement:unknown;apply?:boolean;replaceArtifact?:string}){
 const root=resolve(input.siteRoot);await noToolLinks(root);await noToolLinks(join(root,configPath));
 const placement=browserToolPlacementSchema.parse(input.placement),before=await load(root);
 const candidate=await verifyToolCandidate(input),pin=browserToolPinSchema.parse({...candidate.pinFields,releaseId:input.releaseId});
 if(pin.source.kind!=="github")throw Error("Public installer requires reviewed GitHub source");
 const prior=before.installations.find(x=>x.pin.toolId===pin.toolId);
 if(prior){
  if(input.replaceArtifact!==prior.pin.artifactSha256)throw Error("Update requires exact --replace-artifact of the selected release");
  if(placement.contentId!==prior.placement.contentId||placement.slug!==prior.placement.slug)throw Error("Update must preserve ContentId/route; route migration requires redirects");
  if(pin.releaseId===prior.pin.releaseId)throw Error("Update requires a fresh immutable releaseId");
 }else if(input.replaceArtifact)throw Error("No managed prior installation to replace");
 const next=configuration.parse({schemaVersion:1,installations:[...before.installations.filter(x=>x.pin.toolId!==pin.toolId),{pin,placement}]});
 await checkBrowserToolInstallations(root);await checkIdentity(root,next);
 const existingPage=join(root,"apps/site/src/content/tools",placement.slug+".mdx");
 if(!prior&&(await optional(existingPage)!==null||await optional(join(root,"apps/site/src/content/tools",placement.slug+".md"))!==null))throw Error("Placement already exists; explicit migration required");
 const pkgPath="apps/site/package.json",pkg=JSON.parse(await readFile(join(root,pkgPath),"utf8"));
 if(pkg.dependencies?.[pin.packageName]&&(!prior||pkg.dependencies[pin.packageName]!=="file:../../vendor/browser-tools/"+prior.pin.toolId+"/"+prior.pin.releaseId))throw Error("Dependency already exists; explicit migration required");
 const review=browserToolReviewSchema.parse(input.review),durable=reviewPath(pin),reviewText=json(review),oldReview=await optional(join(root,durable));
 if(oldReview!==null&&oldReview!==reviewText)throw Error("Immutable review path already exists with different bytes");
 const metadataFiles=[configPath,pkgPath,"package-lock.json",durable],previous=new Map<string,string|null>();
 for(const path of new Set([...render(next).keys(),...metadataFiles]))previous.set(path,await optional(join(root,path)));
 const plan={metadataFiles,adoptionDirectory:"vendor/browser-tools/"+pin.toolId+"/"+pin.releaseId,toolId:pin.toolId,releaseId:pin.releaseId,artifactSha256:pin.artifactSha256,route:"/tools/"+placement.slug+"/",draft:true,source:pin.source,
  generatedFiles:[...render(next).keys()],network:false,publication:false,
  nextBuildStep:"npm ci --ignore-scripts (use --offline when the reviewed dependencies are cached), then normal site validation/build",
  capabilityGate:"New capability routes remain draft. Production CSP/publication requires separate reviewed approval."};
 if(!input.apply)return plan;
 // Fixed local artifact adoption only: no source build, remote download or package scripts.
 await adoptToolRelease({...input,review:input.review as never,vendorRoot:join(root,"vendor/browser-tools")});
 const files=await generatedFiles(root,next);files.set(configPath,json(next));
 files.set(durable,reviewText);
 pkg.dependencies[pin.packageName]="file:../../vendor/browser-tools/"+pin.toolId+"/"+pin.releaseId;files.set(pkgPath,json(pkg));
 for(const [path,value]of previous)if(await optional(join(root,path))!==value)throw Error("Installation preimage changed; preserve user edits and re-plan: "+path);
 // Capture all preimages before mutating. Rollback metadata on npm/check failure; immutable adopted release remains unselected.
 try{
  for(const[path,text]of files){await mkdir(dirname(join(root,path)),{recursive:true});await noToolLinks(dirname(join(root,path)));await writeFile(join(root,path),text);}
  execFileSync("npm",["install","--package-lock-only","--ignore-scripts","--offline","--no-audit","--no-fund"],{cwd:root,stdio:"pipe",timeout:60000});
  await checkBrowserToolInstallations(root);
 }catch(error){for(const[path,text]of previous)if(text===null)await rm(join(root,path),{force:true});else await writeFile(join(root,path),text);throw error;}
 return {...plan,applied:true,lockSha256:toolHash(await readFile(join(root,"package-lock.json")))};
}
export async function initializeBrowserToolInstallations(root:string){
 const c=await load(root);for(const[path,text]of await generatedFiles(root,c)){await mkdir(dirname(join(root,path)),{recursive:true});await writeFile(join(root,path),text);}
}

export async function installBrowserTool(input:Parameters<typeof installBrowserToolUnlocked>[0]){
 if(!input.apply)return installBrowserToolUnlocked(input);
 const dir=join(resolve(input.siteRoot),".local");await mkdir(dir,{recursive:true});await noToolLinks(dir);
 const lockPath=join(dir,"browser-tool-install.lock"),lock=await open(lockPath,"wx");
 try{return await installBrowserToolUnlocked(input);}finally{await lock.close();await rm(lockPath);}
}
