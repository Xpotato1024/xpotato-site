export function render(c:Configuration):Map<string,string>{
 const files=new Map<string,string>(),modules:Record<string,unknown>={},bindings:unknown[]=[],pins:BrowserToolPin[]=[],imports:string[]=[],components:string[]=[],manifestImports:string[]=[],manifests:string[]=[];
 const claims=new Map<string,{path:string;owner:string}>();
 const put=(path:string,text:string,owner='registry')=>{
  if(!browserToolPathSchema.safeParse(path.split('/').at(-1)).success)throw Error('Unsafe generated tool filename: '+owner+' ('+path+')');
  const key=path.toLowerCase(),prior=claims.get(key);
  if(prior)throw Error('Case-colliding generated tool paths: '+prior.owner+' / '+owner+' ('+prior.path+' / '+path+')');
  claims.set(key,{path,owner});files.set(path,text);
 };
 for(const [i,item]of c.installations.entries()){
  const {pin,placement:p}=item;
  const componentId=pin.toolId+"-react-v1",base="bt"+i,dir=pin.toolId+"/"+pin.releaseId;
  modules[pin.toolId]=interactiveModuleRecordSchema.parse({id:pin.toolId,framework:"react",componentId,hydration:p.hydration,allowedCollections:["tools"],role:"primary_tool",status:"active",apiVersion:1,budgetClass:"large",releaseId:pin.releaseId});
  bindings.push(toolBindingRecordSchema.parse({contentId:p.contentId,moduleId:pin.toolId,role:"primary_tool",status:"active"}));pins.push(pin);
  const name=componentName(pin.toolId);
  put("apps/site/src/components/islands/"+name+".tsx",(p.display?.integrationLicense?'// SPDX-License-Identifier: '+p.display.integrationLicense+'\n':'// Generated by browser-tools:install.\n')+'export {default} from "'+pin.packageName+'";\n',pin.toolId);
  put("apps/site/src/components/interactive-renderers/"+name+"Styles.astro",'__STYLES__',pin.toolId);
  for(const h of ["load","idle","visible","media"]){
   const wrapper=name+h[0]!.toUpperCase()+h.slice(1);
   imports.push('import '+base+h+' from "../../../components/interactive-renderers/'+wrapper+'.astro";');
   put("apps/site/src/components/interactive-renderers/"+wrapper+".astro",'---\nimport '+name+' from "../islands/'+name+'.js";\nimport '+name+'Styles from "./'+name+'Styles.astro";\n'+
    (h==="media"?'interface Props { mediaQuery?: string }\nconst { mediaQuery } = Astro.props;\nif (!mediaQuery) throw new Error("media hydration requires a registry-owned mediaQuery");\n':'')+
    '---\n<'+name+'Styles />\n<'+name+' client:'+h+(h==="media"?'={mediaQuery}':'')+' />\n',pin.toolId);
  }
  components.push(JSON.stringify(componentId)+":{load:"+base+"load,idle:"+base+"idle,visible:"+base+"visible,media:"+base+"media}");
  manifestImports.push('import '+base+'Manifest from "../../../../../../vendor/browser-tools/'+dir+'/browser-tool.json?raw";');
  manifests.push(JSON.stringify(pin.toolId+":"+pin.releaseId)+":"+base+"Manifest");

 }
 put(generatedRoot+"/records.ts",header+'import {interactiveModuleRecordSchema} from "@xpotato/content-contracts";\nexport const generatedModules = Object.fromEntries(Object.entries('+JSON.stringify(modules,null,2)+').map(([key,value])=>[key,interactiveModuleRecordSchema.parse(value)]));\nexport const generatedBindings = '+JSON.stringify(bindings,null,2)+' as const;\nexport const generatedReleases = '+JSON.stringify(pins,null,2)+' as const;\nexport const generatedComponentIds = '+JSON.stringify(c.installations.map(x=>x.pin.toolId+"-react-v1"))+' as const;\n');
 put(generatedRoot+"/components.ts",header+imports.join("\n")+'\nexport const generatedComponents = {'+components.join(",")+'};\n');
 put(generatedRoot+"/manifests.ts",header+manifestImports.join("\n")+'\nexport const generatedManifestSources = {'+manifests.join(",")+'};\n');
 put(generatedRoot+"/display.ts",header+'export const generatedToolDisplayPolicies = '+JSON.stringify(Object.fromEntries(c.installations.filter(x=>x.placement.display).map(x=>[x.pin.toolId,x.placement.display])),null,2)+' as const;\n');
 return files;
}
export async function generatedFiles(root:string,c:Configuration){
 const files=render(c);
 for(const item of c.installations){
  const {pin}=item;
  const manifest=await verifyToolPin(join(root,"vendor/browser-tools"),pin);
  const display=item.placement.display;
  await assertToolDisplayPolicy(root,pin.toolId,manifest.license.spdx,display);
  const names=new Set<string>();for(const notice of display?.additionalNotices??[]){
   if(!manifest.license.additional?.includes(notice.file))throw Error('Display notice must belong to the exact release license set');
   const name=notice.file.split('/').at(-1)!;if(names.has(name))throw Error('Duplicate public license basename');names.add(name);
   const path='apps/site/public/tool-licenses/'+pin.toolId+'-v'+manifest.version+'/'+name;
   files.set(path,toolLicenseText(await readFile(join(root,'vendor/browser-tools',pin.toolId,pin.releaseId,notice.file))));
  }
  const name=componentName(pin.toolId);
  const styles=manifest.integration.styles;
  files.set("apps/site/src/components/interactive-renderers/"+name+"Styles.astro",'---\n// A URL asset is emitted once; importing every renderer must not load tool CSS on articles.\n'+
   styles.map((style,i)=>'import styles'+(styles.length===1?'':i)+' from "../../../../../vendor/browser-tools/'+pin.toolId+'/'+pin.releaseId+'/'+style+'?url";').join('\n')+
   '\n---\n'+styles.map((_,i)=>'<link rel="stylesheet" href={styles'+(styles.length===1?'':i)+'} data-tool-styles="'+pin.toolId+'" />').join('\n')+'\n');

 }
 return files;
}
export async function assertToolDisplayPolicy(root:string,toolId:string,upstreamLicense:string,display?:z.infer<typeof toolDisplayPolicySchema>){
 const notices=display?.additionalNotices??[];
 if(new Set(notices.map(n=>n.file.split('/').at(-1)!.toLowerCase())).size!==notices.length)throw Error('Case-colliding public notice basenames');
 if((upstreamLicense.startsWith('AGPL-')||display?.integrationLicense?.startsWith('AGPL-'))&&(!display?.integrationSourceOffer||!display.integrationLicense))throw Error('AGPL integration source offer and explicit host license required');
 if(display?.integrationSourceOffer){
  if(display.integrationSourceOffer!=='apps/site/licenses/'+toolId+'/SOURCE_OFFER.md')throw Error('Integration offer belongs to another tool');
  await noToolLinks(join(root,display.integrationSourceOffer));if(!(await readFile(join(root,display.integrationSourceOffer),'utf8')).trim())throw Error('Empty integration source offer');
 }
}
export async function checkIdentity(root:string,c:Configuration,planned?:{pages:ReadonlyMap<string,string>;admissions:ReadonlyMap<string,BrowserToolPin>}){
 const pageAt=(path:string)=>planned?.pages.has(path)?Promise.resolve(planned.pages.get(path)!):optional(join(root,path));
 const keys=new Set<string>(),ids=new Set<string>(),routes=new Set<string>();
 // Detect handwritten registration collisions; every managed tool uses the generated records.
 const legacy=await readFile(join(root,"apps/site/src/content-registry/interactive/index.ts"),"utf8"),manual=new Set<string>();
 const ast=ts.createSourceFile("index.ts",legacy,ts.ScriptTarget.Latest,true,ts.ScriptKind.TS);let registryFound=false;
 const scan=(node:ts.Node):void=>{
  if(ts.isVariableDeclaration(node)&&ts.isIdentifier(node.name)&&node.name.text==="interactiveModuleRegistry"&&node.initializer
   &&ts.isCallExpression(node.initializer)&&node.initializer.arguments[0]&&ts.isObjectLiteralExpression(node.initializer.arguments[0])){
   registryFound=true;for(const prop of node.initializer.arguments[0].properties){
    if(ts.isSpreadAssignment(prop)&&prop.expression.getText(ast)==="generatedModules")continue;
    if(!ts.isPropertyAssignment(prop)||!(ts.isIdentifier(prop.name)||ts.isStringLiteral(prop.name)))throw Error("Unknown manual registry shape; explicit migration required");
    manual.add(prop.name.text);
   }
  }ts.forEachChild(node,scan);
 };scan(ast);if(!registryFound)throw Error("Manual registry shape not recognized");
 if(manual.size)throw Error('Tool modules must use the common installer, not handwritten registration');
 for(const item of c.installations){
  const {pin,placement:p}=item;
  if(manual.has(pin.toolId)||keys.has(pin.toolId)||ids.has(p.contentId)||routes.has(p.slug))throw Error("Duplicate tool, ContentId or route");
  const page=await pageAt("apps/site/src/content/tools/"+p.slug+".mdx");
  // New placements are checked before creation; installed pages are checked here
  // and never regenerated by release updates.
  if(page!==null){
   const metadata=toolFrontmatterSchema.parse(parseYaml(page.split(/^---\s*$/mu)[1]??""));
   if(metadata.id!==p.contentId)throw Error("Tool content identity differs from registration");
   if(!metadata.draft){
    const admission=planned?.admissions.get(pin.toolId);
    if(admission){
     const review=JSON.parse(planned?.pages.get(reviewPath(pin))??await readFile(join(root,reviewPath(pin)),"utf8"));
     assertToolPublicAdmission(pin,review,admission);
    }else if(!(await admitsPublicTool(pin,root)))throw Error("Published tool requires an exact reviewed public admission");
   }
  }
  keys.add(pin.toolId);ids.add(p.contentId);routes.add(p.slug);
 }
 // Identity collision check includes held/draft content, not just published catalog.
 const content=join(root,"apps/site/src/content");
 async function walk(dir:string){for(const e of await readdir(dir,{withFileTypes:true})){
  const path=join(dir,e.name);if(e.isSymbolicLink())throw Error("Content links forbidden");if(e.isDirectory())await walk(path);else if(/\.mdx?$/u.test(e.name)){
   const owned=c.installations.find(x=>path===join(content,"tools",x.placement.slug+".mdx"));if(owned)continue;
   const text=await readFile(path,"utf8");for(const id of ids)if(text.includes(id))throw Error("ContentId already used");
  }
 }}await walk(content);
 // Registry terms must exist; never silently allocate taxonomy.
 const source=await readFile(join(root,"apps/site/src/content-registry/taxonomy/phase5-generated.ts"),"utf8");
 const taxonomy=taxonomyRegistrySchema.parse(JSON.parse(source.slice(source.indexOf("{"),source.lastIndexOf("}")+1)));
 for(const {placement:p}of c.installations){
  const page=await pageAt("apps/site/src/content/tools/"+p.slug+".mdx");if(page===null)continue;
  const fm=toolFrontmatterSchema.parse(parseYaml(page.split(/^---\s*$/mu)[1]??""));
  if(!taxonomy.toolCategories.some(t=>t.id===fm.category&&t.status==="active")||fm.tags.some(t=>!taxonomy.tags.some(x=>x.id===t&&x.status==="active")))throw Error("Unknown/inactive Tools taxonomy");
 }
}
export async function checkBrowserToolInstallations(root:string):Promise<void>{
 const c=await load(root);await checkIdentity(root,c);
 const history=parseToolReleaseHistory(await readFile(join(root,"apps/site/src/content-registry/interactive/releases.ts"),"utf8"));
 const keys=new Set(c.installations.map(i=>i.pin.toolId+":"+i.pin.releaseId));for(const pin of history){const key=pin.toolId+":"+pin.releaseId;if(keys.has(key))throw Error("Duplicate historical release identity");keys.add(key);await verifyRetainedToolPin(root,pin);}
 for(const {placement:p}of c.installations)if(await optional(join(root,"apps/site/src/content/tools/",p.slug+".mdx"))===null)throw Error("Installed tool page missing");const files=await generatedFiles(root,c);
 for(const[path,text]of files)if(await optional(join(root,path))!==text)throw Error("Stale generated installation: "+path);
 let count=0;
 async function exact(dir:string){for(const e of await readdir(join(root,dir),{withFileTypes:true})){
  if(++count>256)throw Error("Generated directory exceeds budget");
  const path=dir+"/"+e.name;await noToolLinks(join(root,path));
  if(e.isDirectory())await exact(path);else if(!e.isFile()||!files.has(path))throw Error("Unmanaged generated file collision: "+path);
 }}await exact(generatedRoot);
 for(const {pin}of c.installations){
  await noToolLinks(join(root,reviewPath(pin)));
  const review=browserToolReviewSchema.parse(JSON.parse(await readFile(join(root,reviewPath(pin)),"utf8")));
  if((review.source.kind==="local-fixture")!==(review.review.scope==="fixture-only")||toolHash(JSON.stringify(review))!==pin.reviewSha256
   ||JSON.stringify(review.source)!==JSON.stringify(pin.source)
   ||(["sourceCommit","sourceTreeSha256","lockSha256","manifestSha256","artifactSha256"] as const).some(key=>review[key]!==pin[key])
   ||review.reproducibleArtifactSha256.some(hash=>hash!==pin.artifactSha256))throw Error("Durable review identity/hashes do not match pin");
  const pkg=JSON.parse(await readFile(join(root,"apps/site/package.json"),"utf8"));
  const vendor="vendor/browser-tools/"+pin.toolId+"/"+pin.releaseId,dependency="file:../../"+vendor;
  if(pkg.dependencies?.[pin.packageName]!==dependency)throw Error("Installation dependency differs");
  const lock=JSON.parse(await readFile(join(root,"package-lock.json"),"utf8")),manifest=JSON.parse(await readFile(join(root,vendor,"browser-tool.json"),"utf8"));
  if(manifest.runtime.profile==="bounded-browser-v2"&&!review.runtimeReview)throw Error("Durable bounded runtime review required");
  if(lock.packages?.["apps/site"]?.dependencies?.[pin.packageName]!==dependency
   ||lock.packages?.["node_modules/"+pin.packageName]?.resolved!==vendor||lock.packages?.["node_modules/"+pin.packageName]?.link!==true
   ||lock.packages?.[vendor]?.name!==pin.packageName||lock.packages?.[vendor]?.version!==manifest.version)throw Error("Installation lock differs from selected artifact");
 }
}
