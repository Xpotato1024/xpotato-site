import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile,mkdtemp,mkdir,writeFile,copyFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import {siteIconPublicObjects,assertSiteIconPublicObject,assertHomeWorkshopPublicObjects,homeWorkshopPublicObjects,assertHomeWorkshopImageReferences} from './home-workshop-public-policy.mjs';
import {readPublicTargets} from './manual-deployment.mjs';
import {authority} from './deployment-policy.mjs';

const expected={path:'/icon-apple-touch.png',bytes:2806,sha256:'ebff5c6425f47e6aa23f2e4b2a9af3d32ebe987f1fd52e0d3b52a743e0cc94be'};

test('touch icon admission pins exact generated bytes and does not expand the photo set',async()=>{
  const bytes=await readFile(new URL('../../../apps/site/public/icon-apple-touch.png',import.meta.url));
  assert.equal(bytes.length,expected.bytes);
  assert.equal(createHash('sha256').update(bytes).digest('hex'),expected.sha256);
  assert.deepEqual(siteIconPublicObjects,[expected]);
  assert.ok(Object.isFrozen(siteIconPublicObjects)&&Object.isFrozen(siteIconPublicObjects[0]));
  assert.equal(assertSiteIconPublicObject({...expected}),siteIconPublicObjects[0]);
  assert.throws(()=>assertHomeWorkshopPublicObjects([...homeWorkshopPublicObjects,expected]),/HOME_WORKSHOP_PHOTO_SET/);
  for(const row of [{...expected,bytes:1},{...expected,sha256:'0'.repeat(64)},{...expected,other:true},...['/private.png','/icon-other.png',expected.path+'?x=1',expected.path+'#x',expected.path.toUpperCase()].map(path=>({...expected,path}))]) {
    assert.throws(()=>assertSiteIconPublicObject(row),/UNAPPROVED_RASTER/);
  }
});

test('touch icon image references still require exact path, same origin and checked bytes',()=>{
  const assets=new Map([[expected.path,expected]]);
  assert.doesNotThrow(()=>assertHomeWorkshopImageReferences('<img src="'+expected.path+'">','/',assets,authority.hostname));
  for(const value of ['https://example.test'+expected.path,expected.path+'?x=1',expected.path+'#x','/extra/..'+expected.path,'/%69con-apple-touch.png']) {
    assert.throws(()=>assertHomeWorkshopImageReferences('<img src="'+value+'">','/',assets,authority.hostname),/UNAPPROVED_IMAGE_REFERENCE/);
  }
  assert.throws(()=>assertHomeWorkshopImageReferences('<img src="'+expected.path+'">','/',new Map(),authority.hostname),/UNAPPROVED_IMAGE_REFERENCE/);
});

test('synthetic artifact scan accepts only the exact touch PNG without weakening required photos',async()=>{
  const root=await mkdtemp(join(tmpdir(),'site-icon-test-')),dist=join(root,'apps/site/dist');
  const selection={sourceSha:'a'.repeat(40),artifactId:'12',digest:'sha256:'+'d'.repeat(64),runId:'11',runAttempt:1};
  const held=Array.from({length:44},(_,i)=>i.toString(16).padStart(8,'0')+'-0000-4000-8000-000000000000');
  try {
    await mkdir(dist,{recursive:true});
    await writeFile(join(root,'release.json'),JSON.stringify({sourceSha:selection.sourceSha,productionEligible:true,event:'push',gitRef:'refs/heads/main',workflowRunId:selection.runId,workflowRunAttempt:1,serverAuthoritySha:authority.serverSha,wranglerVersion:authority.wrangler,validation:{source:'PASS',final:'PASS'}}));
    await writeFile(join(root,'apps/site/wrangler.jsonc'),JSON.stringify({name:authority.worker,compatibility_date:'2026-01-01',workers_dev:false,preview_urls:false,assets:{directory:'./dist',not_found_handling:'404-page'}}));
    await copyFile(new URL('../../../apps/site/public/icon-apple-touch.png',import.meta.url),join(dist,expected.path.slice(1)));
    await assert.rejects(()=>readPublicTargets(root,selection,held),/HOME_WORKSHOP_PHOTO_SET/);
    await writeFile(join(dist,expected.path.slice(1)),'tampered');
    await assert.rejects(()=>readPublicTargets(root,selection,held),/UNAPPROVED_RASTER/);
  } finally { await rm(root,{recursive:true,force:true}); }
});
